logger = logging.getLogger("repomind.testing.generator")


class TestCodeGenerator:
    """
    Generates runnable unit, integration, and edge-case test code for a TestScenario.
    """
    __test__ = False

    def __init__(self, db: Session):
        self.db = db

    def generate_for_scenario(
        self,
        scenario_id: int,
        framework: Optional[str] = None,
        language: Optional[str] = None,
    ) -> GeneratedTestCase:
        """
        Generates concrete test code for the given TestScenario and persists
        the GeneratedTestCase with execution_status='pending'.
        """
        scenario = self.db.get(TestScenario, scenario_id)
        if not scenario:
            raise ValueError(f"TestScenario {scenario_id} not found")

        # Determine language and framework
        target_file = scenario.target_file
        if not language:
            if target_file.endswith(".py"):
                language = "python"
            elif target_file.endswith(".ts") or target_file.endswith(".tsx"):
                language = "typescript"
            else:
                language = "javascript"

        if not framework:
            framework = "pytest" if language == "python" else "vitest"

        # Determine target test file path
        base_name = target_file.split("/")[-1].split(".")[0]
        if scenario.existing_test_file:
            test_file_path = scenario.existing_test_file
        else:
            if language == "python":
                test_file_path = f"backend/tests/test_{base_name}_{scenario.category}.py"
            else:
                ext = ".ts" if language == "typescript" else ".jsx" if target_file.endswith(".jsx") else ".js"
                test_file_path = f"frontend/tests/{base_name}_{scenario.category}.test{ext}"

        # Generate test code
        test_code = self._produce_test_code(scenario, language, framework)

        # Create record with status='pending'
        # Crucial Rule: Do not report generated tests as passing until executed.
        generated_case = GeneratedTestCase(
            test_scenario_id=scenario.id,
            language=language,
            framework=framework,
            test_file_path=test_file_path,
            test_code=test_code,
            execution_status="pending",
            execution_result=None,
            security_reviewed=False,
            created_at=datetime.now(timezone.utc),
        )

        self.db.add(generated_case)
        self.db.commit()
        self.db.refresh(generated_case)

        logger.info(
            "Generated test case %d for scenario %d (%s, %s)",
            generated_case.id,
            scenario.id,
            language,
            framework,
        )
        return generated_case

    def _produce_test_code(self, scenario: TestScenario, language: str, framework: str) -> str:
        """
        Synthesizes the test code with clean imports, fixtures, and assertions.
        """
        if language == "python":
            return self._produce_python_test(scenario)
        else:
            return self._produce_js_test(scenario, framework)

